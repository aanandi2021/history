"""Bundle this repo's Spec Kit artifacts into docs/speckit/artifacts.js for the walkthrough page.

Usage: python scripts/build_walkthrough.py
The page reads window.ARTIFACTS so it works from file:// with no server. Re-run after editing specs.
"""
import json, os, subprocess, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [
    ".specify/memory/constitution.md",
    "specs/001-world-viewer/spec.md",
    "specs/001-world-viewer/checklists/requirements.md",
    "specs/001-world-viewer/plan.md",
    "specs/001-world-viewer/research.md",
    "specs/001-world-viewer/data-model.md",
    "specs/001-world-viewer/contracts/url-hash.md",
    "specs/001-world-viewer/contracts/dataset.schema.json",
    "specs/001-world-viewer/quickstart.md",
    "specs/001-world-viewer/tasks.md",
    "specs/001-world-viewer/analysis.md",
    "README.md",
]


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8").stdout


def main():
    files = {}
    for f in FILES:
        p = os.path.join(ROOT, *f.split("/"))
        if os.path.exists(p):
            with open(p, encoding="utf-8") as fh:
                files[f] = fh.read()
    commits = []
    log = git("log", "--reverse", "--date=short", "--pretty=format:%h\x1f%ad\x1f%s", "--shortstat")
    cur = None
    for line in log.splitlines():
        if "\x1f" in line:
            h, d, s = line.split("\x1f", 2)
            cur = {"hash": h, "date": d, "subject": s, "stat": ""}
            commits.append(cur)
        elif line.strip() and cur:
            cur["stat"] = line.strip()
    out = {
        "built": datetime.date.today().isoformat(),
        "repo": "aanandi2021/history",
        "files": files,
        "commits": commits,
    }
    dest = os.path.join(ROOT, "docs", "speckit", "artifacts.js")
    with open(dest, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by scripts/build_walkthrough.py. Do not edit by hand.\n")
        fh.write("window.ARTIFACTS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    print(f"wrote {dest}: {len(files)} files, {len(commits)} commits")


if __name__ == "__main__":
    main()
