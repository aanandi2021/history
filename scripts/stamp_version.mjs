// Write app/version.js from package.json and git, so every build says what it is.
//   node scripts/stamp_version.mjs          (also run by `npm run stamp`)
// The viewer, atlas, board and walkthrough show it as a small badge; tests check it matches package.json.
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const git = (cmd) => { try { return execSync(`git ${cmd}`, { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return ""; } };
const now = new Date(), pad = (n) => String(n).padStart(2, "0");
const info = {
  version: pkg.version,
  commit: git("rev-parse --short HEAD"),
  branch: git("rev-parse --abbrev-ref HEAD"),
  stamped: `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}`
};
const out = `// Generated by scripts/stamp_version.mjs. Do not edit by hand.\nwindow.APP_VERSION = ${JSON.stringify(info)};\n`;
fs.writeFileSync(path.join(root, "app", "version.js"), out);
console.log(`app/version.js: v${info.version} (${info.branch} ${info.commit}, ${info.stamped})`);
